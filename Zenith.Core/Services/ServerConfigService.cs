using System;
using System.Collections.Generic;
using System.IO;
using System.Text;
using Zenith.Core.Models;

namespace Zenith.Core.Services
{
    public class SpecificEngineConfig
    {
        public string FileName { get; set; } = string.Empty;
        public string Title { get; set; } = string.Empty;
        public string Content { get; set; } = string.Empty;
        public Dictionary<string, string> SimpleSettings { get; set; } = new();
    }

    public class ServerConfigService
    {
        public ServerPropertiesConfig LoadProperties(string serverDirectory)
        {
            var config = new ServerPropertiesConfig();
            string filePath = Path.Combine(serverDirectory, "server.properties");
            if (File.Exists(filePath))
            {
                config.LoadFromFile(filePath);
            }
            return config;
        }

        public void SaveProperties(string serverDirectory, ServerPropertiesConfig config)
        {
            string filePath = Path.Combine(serverDirectory, "server.properties");
            config.SaveToFile(filePath);
        }

        public bool CheckEulaAccepted(string serverDirectory)
        {
            string eulaPath = Path.Combine(serverDirectory, "eula.txt");
            if (!File.Exists(eulaPath)) return false;

            string content = File.ReadAllText(eulaPath);
            return content.Contains("eula=true", StringComparison.OrdinalIgnoreCase);
        }

        public void SetEulaAccepted(string serverDirectory, bool accepted)
        {
            string eulaPath = Path.Combine(serverDirectory, "eula.txt");
            string content = $"#By changing the setting below to TRUE you are indicating your agreement to our EULA (https://aka.ms/MinecraftEULA).\n#Generated by Zenith MC Server Launcher\neula={accepted.ToString().ToLowerInvariant()}\n";
            File.WriteAllText(eulaPath, content, Encoding.UTF8);
        }

        public SpecificEngineConfig LoadSpecificConfig(string serverDirectory, string fileName, string defaultConfigTemplate)
        {
            string filePath = Path.Combine(serverDirectory, fileName);
            string content = File.Exists(filePath) ? File.ReadAllText(filePath, Encoding.UTF8) : defaultConfigTemplate;

            var config = new SpecificEngineConfig
            {
                FileName = fileName,
                Title = Path.GetFileNameWithoutExtension(fileName).ToUpperInvariant(),
                Content = content
            };

            return config;
        }

        public void SaveSpecificConfig(string serverDirectory, string fileName, string content)
        {
            string filePath = Path.Combine(serverDirectory, fileName);
            File.WriteAllText(filePath, content, Encoding.UTF8);
        }

        public string GetLaunchArguments(string jarFileName, int ramGb = 4, string customArgs = "")
        {
            StringBuilder sb = new StringBuilder();
            sb.Append($"-Xms{ramGb}G -Xmx{ramGb}G ");
            if (!string.IsNullOrWhiteSpace(customArgs))
            {
                sb.Append($"{customArgs.Trim()} ");
            }
            sb.Append($"-jar \"{jarFileName}\" nogui");
            return sb.ToString();
        }
    }
}
